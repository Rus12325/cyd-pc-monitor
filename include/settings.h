#pragma once
// ============================================================
// Редактируемые пороги (страница CTRL / тревоги).
// Значения по умолчанию — из config.h, но ПК-приложение может
// менять их на лету строкой  THR:r1on=60,r1off=55,r2on=65,
// r2off=60,warn=60,crit=75  — без перепрошивки.
// Хранятся во флеше (NVS), переживают перезагрузку.
// ============================================================
#include <Arduino.h>

// Инициализация (загрузка из NVS или значения по умолчанию)
void settingsInit();

// Порог включения реле r (0/1), C: включить при t >= on
float settingsRelayOn(int r);
// Порог выключения реле r (0/1), C: выключить при t <= off
float settingsRelayOff(int r);
// Цветовая зона WARN (жёлтый) / тревога ALARM (красный+зуммер), C
float settingsWarnC();
float settingsCritC();

// Применить строку "key=value,key=value,..." (без префикса THR:).
// Возвращает true, если что-то изменилось (нужна перерисовка).
bool settingsApplyLine(const String& body);
