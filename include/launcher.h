#pragma once
// ============================================================
// Быстрый запуск приложений (страница APPS): до 8 кнопок.
// На экране — только ПОДПИСИ (команды живут в ПК-приложении,
// оно же их и исполняет по строке "APP:n"). Настройка списка
// делается в окне ПК (кнопка «Запуск APPS…»), оттуда подписи
// приходят строкой:
//   AP:<номер>=<подпись>        (например AP:0=Explorer)
// Подписи хранятся во флеше (NVS), чтобы вкладка выглядела
// одинаково до прихода ПК.
// ============================================================
#include <Arduino.h>

#define APP_MAX     8
#define APP_LABEL_L 17

struct AppItem {
    char label[APP_LABEL_L];
};

// Загрузить подписи из NVS (или значения по умолчанию)
void appInit();

// Разобрать строку "N=label" и сохранить (NVS + RAM).
// Возвращает true, если что-то изменилось (нужна перерисовка).
bool appApplyLine(const String& body);

// Получить кнопку по номеру (0..APP_MAX-1)
const AppItem& appGet(int i);
